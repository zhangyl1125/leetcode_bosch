# 题目要求在一个数组中找出所有 数值不重复的三元组，使它们的和为 0（即 a + b + c = 0）。
# 难点不是“找和为 0”,而是“不能重复”
"""
生活比喻：天平称重（目标总和为 0）
排好序后，队伍是从小到大排列的：左边都是小数字/负数，右边都是大数字/正数。
你选好第 1 个人 i 站上天平，然后让剩下这排人的最左边（最小的数 left）和最右边（最大的数 right）也站上去：
    如果三人总和太轻了（< 0）： 说明负数太大或正数太小，需要换一个更大的数来增重。因为右边已经到头了，只能让左边的指针往右走一步（left += 1）。
    如果三人总和太重了（> 0）： 说明正数太大了，需要换一个更小的数来减重。让右边的指针往左走一步（right -= 1）。
    如果刚好等于 0： 记下这组答案！然后两边指针同时往中间收缩，去寻找下一组可能的搭配。


"""
# 常用双指针：先排序，再一左一右夹逼
# 哈希法也能做，但去重很麻烦；双指针法更自然，也更高效。双指针法

# 解题思路： 
# “先排序，固定一个锚点，两头往中间夹逼。”


"""
核心三步走
1.先排个序（nums.sort()）数组变得从小到大排列。排序的好处极大：
    相同的数字挨在一起，去重极方便；
    和如果太小，左边指针往右移就能变大；和如果太大，右边指针往左移就能变小。
2.固定基准数 a（nums[i]）
    用外层循环挨个选定三元组的第一个数。
3.双指针找另外两个数（left 和 right）
    left 指向基准数右边紧挨着的位置（较小的数）；
    right 指向整个数组的最末尾（最大的数）；
    两人根据当前三数之和与 0 的差距，向中间走动。
"""


class Solution:
    def threesum(self,nums:list[int])->list[list[int]]:
        result = []  # 用于存储所有符合条件的三元组
        nums.sort()  # 先对数组进行排序，方便去重和双指

        for i in range(len(nums)):
            # 如果第一个元素大于0，不需要进一步检查
            if nums[i] > 0:
                # 因为数组已经排序，后面的数都大于0，不可能再有和为0的三元组
                return result  

            # 如果当前元素与前一个元素相同，跳过，避免重复计算
            if i > 0 and nums[i] == nums[i - 1]:
                continue  

            left = i + 1  # 左指针初始化为当前元素的下一个位置
            right = len(nums) - 1  # 右指针初始化为数组的最后一个位置

            while right > left:  # 当右指针大于左指针时，继续查找
                total = nums[i] + nums[left] + nums[right]  # 计算当前三元组的和

                if total < 0:  # 如果和小于0，说明需要更大的数
                    left += 1  # 左指针右移，增大总和
                elif total > 0:  # 如果和大于0，说明需要更小的数
                    right -= 1  # 右指针左移，减小总和
                else:  # 找到一个符合条件的三元组
                    result.append([nums[i], nums[left], nums[right]])  # 将三元组加入结果列表

                    # 跳过相同的元素以避免重复
                    while right > left and nums[right] == nums[right - 1]:
                        right -= 1  # 右指针左移，跳过重复元素
                    while right > left and nums[left] == nums[left + 1]:
                        left += 1  # 左指针右移，跳过重复元素

                    right -= 1  # 移动右指针，继续查找其他可能的三元组
                    left += 1  # 移动左指针，继续查找其他可能的三元组
        return result  # 返回所有符合条件的三元组


if __name__ == '__main__':
    solution = Solution()
    print(solution.threesum([-1, 0, 1, 2, -1, -4]))  # 输出 [[-1, -1, 2], [-1, 0, 1]]
    print(solution.threesum([0, 0, 0]))              # 输出 [[0, 0, 0]]
    print(solution.threesum([-2, 0, 1, 1, 2]))      # 输出 [[-2, 0, 2], [-2, 1, 1]]


"""
输入：nums = [-1, 0, 1, 2, -1, -4]
1.排序后： [-4, -1, -1, 0, 1, 2]
2.i = 0 时（nums[0] = -4）：
    left 指向 nums[1] = -1，right 指向 nums[5] = 2。
    即使挑当前最大的两个数相加：-4 + 1 + 2 = -1 < 0，无论怎么挪双指针都不可能凑成 0。
3.i = 1 时（nums[1] = -1）：
    初始位置：left = 2 (值为 -1)，right = 5 (值为 2)。
    第 1 次求和： $(-1) + (-1) + 2 = 0$ $\to$ 命中答案 [-1, -1, 2]！
        检查去重：nums[right] 前一个数是 1，不重复；nums[left] 后一个数是 0，不重复。
        双指针各进退一步：left = 3 (值为 0)，right = 4 (值为 1)。
    第 2 次求和： (-1) + 0 + 1 = 0 $\to$ 再次命中答案 [-1, 0, 1]！双指针继续收缩，此时 left 与 right 相遇交叉，内层循环结束。
4. i = 2 时（nums[2] = -1）：nums[2] == nums[1]（值都为 -1），触发 i > 0 and nums[i] == nums[i - 1]，直接跳过。
后续 i = 3, 4, 5 均无法凑成 0，最终返回：[[-1, -1, 2], [-1, 0, 1]]。

"""